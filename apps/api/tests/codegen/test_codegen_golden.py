# --------------------------------------------------------------------------
# node-grouping guardrail — a top-level ``groups`` key is a render-only editor
# overlay and MUST be INVISIBLE to codegen. The generated MQL5 has to be
# BYTE-IDENTICAL whether or not the graph carries ``groups``. This locks the
# "codegen no-op" invariant for the node-grouping feature.
# --------------------------------------------------------------------------
def test_groups_key_is_byte_identical_codegen_noop() -> None:
    base = {
        "nodes": [
            {"id": "1", "type": "Start", "data": {}},
            {"id": "2", "type": "SMA", "data": {"period": 50}},
            {"id": "3", "type": "Condition",
             "data": {"left": "sma_2[0]", "operator": ">", "right": "1.2345"}},
            {"id": "4", "type": "Buy", "data": {"lots": 0.1}},
            {"id": "5", "type": "End", "data": {}},
        ],
        "edges": [
            {"source": "1", "target": "2"},
            {"source": "2", "target": "3"},
            {"source": "3", "target": "4"},
            {"source": "4", "target": "5"},
        ],
    }
    # Same graph, plus a render-only ``groups`` overlay referencing real members.
    with_groups = {
        **base,
        "groups": [{"id": "g1", "name": "Entry", "nodeIds": ["2", "3"]}],
    }

    without = generate_mql5(base, ea_name="GroupNoOpEA")
    withg = generate_mql5(with_groups, ea_name="GroupNoOpEA")
    assert withg == without
