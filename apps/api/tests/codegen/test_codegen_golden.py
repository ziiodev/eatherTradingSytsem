"""Byte-identity GOLDEN tests for the MQL5 codegen engine.

These lock the EXACT generated MQL5 string for a representative set of graphs
(SMA / RSI / MACD operands, a Stochastic %K/%D graph, and crossing graphs that
exercise the ``[s]``/``[s+1]`` indices plus the ``s+2`` copy depth). They are the
acceptance gate for the indicator-multi-output FOUNDATION refactor: every change
in that effort is additive and DORMANT-by-default, so each golden below MUST stay
byte-identical before and after the refactor.

Do NOT edit a golden to "fix" a failing test — a diff here means the refactor
changed an existing graph's output, which violates the byte-identity invariant.
"""

from __future__ import annotations

from aether_api.services.codegen import generate_mql5


def _wrap(ea_name: str, body: str) -> str:
    """Return the full EA file for ``body`` lines inside ``OnTick``.

    The title-box trailing pad is a FIXED 24 spaces regardless of EA-name length
    (the current generator does not realign the border), captured verbatim from
    the generator output.
    """
    pad = " " * 24
    return (
        "//+------------------------------------------------------------------+\n"
        f"//| {ea_name}.mq5 — generated by TechainClone{pad}|\n"
        "//+------------------------------------------------------------------+\n"
        "#property strict\n"
        "#include <Trade/Trade.mqh>\n"
        "\n"
        "CTrade trade;\n"
        "\n"
        "int OnInit()\n"
        "{\n"
        "   return(INIT_SUCCEEDED);\n"
        "}\n"
        "\n"
        "void OnDeinit(const int reason)\n"
        "{\n"
        "}\n"
        "\n"
        "void OnTick()\n"
        "{\n"
        f"{body}\n"
        "}\n"
    )


# --------------------------------------------------------------------------
# Task 0.1 — SMA operand graph (sma_<id>[0])
# --------------------------------------------------------------------------
def test_golden_sma_operand_graph() -> None:
    graph = {
        "nodes": [
            {"id": "1", "type": "Start", "data": {}},
            {"id": "2", "type": "SMA", "data": {"period": 50}},
            {"id": "3", "type": "Condition",
             "data": {"left": "sma_2[0]", "operator": ">", "right": "1.2345"}},
            {"id": "4", "type": "Buy", "data": {"lots": 0.1}},
            {"id": "5", "type": "End", "data": {}},
        ],
        "edges": [
            {"source": "1", "target": "2"},
            {"source": "2", "target": "3"},
            {"source": "3", "target": "4"},
            {"source": "4", "target": "5"},
        ],
    }
    body = (
        "   // [Start] node id=1\n"
        "   // --- Strategy logic begins ---\n"
        "   // [SMA] node id=2\n"
        "   double sma_2[];\n"
        "   int h_sma_2 = iMA(_Symbol, _Period, 50, 0, MODE_SMA, PRICE_CLOSE);\n"
        "   CopyBuffer(h_sma_2, 0, 0, 1, sma_2);\n"
        "   // [Condition] node id=3\n"
        "   if (!(sma_2[0] > 1.2345)) return;\n"
        "   // [Buy] node id=4\n"
        '   trade.Buy(0.1, _Symbol, 0.0, 0, 0, "buy");\n'
        "   // [End] node id=5\n"
        "   // --- Strategy logic ends ---"
    )
    assert generate_mql5(graph, ea_name="GoldSmaEA") == _wrap("GoldSmaEA", body)


